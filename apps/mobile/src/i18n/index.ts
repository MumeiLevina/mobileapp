import { usePreferences } from "../store/preferences";
import { english } from "./messages";
export function useTranslate() {
  const locale = usePreferences((s) => s.locale);
  return (value: string) =>
    locale === "en"
      ? (english[value] ?? english[value.replace(/\s+/g, " ").trim()] ?? value)
      : value;
}
